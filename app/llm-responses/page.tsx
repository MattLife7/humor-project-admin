import Link from "next/link";
import LogoutButton from "../logout-button";
import { requireSuperadmin } from "@/lib/auth/require-superadmin";

export const instant = false;

export default async function LlmResponsesPage() {
  const {
    supabase,
    authorized,
    reason,
  } = await requireSuperadmin();

  if (!authorized) {
    return (
      <main className="flex min-h-screen items-center justify-center bg-gray-100 px-6">
        <div className="w-full max-w-md rounded-2xl bg-white p-8 shadow-lg">
          <h1 className="text-3xl font-bold">
            {reason === "not_authenticated"
              ? "Admin login required"
              : "Access denied"}
          </h1>

          <div className="mt-6">
            <Link
              href="/"
              className="rounded-lg bg-black px-4 py-2 font-semibold text-white"
            >
              Back home
            </Link>
          </div>
        </div>
      </main>
    );
  }

  const { data: responses, error } = await supabase
    .from("llm_responses")
    .select(`
      id,
      response_text,
      created_at,
      generation_request_id,
      model_id,
      llm_models (
        name,
        model_key,
        llm_providers (
          name
        )
      ),
      generation_requests (
        status
      )
    `)
    .order("created_at", { ascending: false });

  if (error) {
    return (
      <main className="min-h-screen bg-gray-100 p-8">
        <p className="text-red-600">
          {error.message}
        </p>
      </main>
    );
  }

  return (
    <main className="min-h-screen bg-gray-100 p-6 sm:p-8">
      <div className="mx-auto max-w-7xl">
        <header className="flex flex-wrap items-center justify-between gap-4">
          <div>
            <p className="text-sm font-semibold uppercase tracking-wide text-gray-500">
              Rate My Bite Admin
            </p>

            <h1 className="mt-1 text-4xl font-bold">
              LLM Responses
            </h1>

            <p className="mt-2 text-gray-600">
              View AI responses generated by configured LLM models.
            </p>
          </div>

          <div className="flex gap-3">
            <Link
              href="/"
              className="rounded-lg border border-gray-300 bg-white px-4 py-2 text-sm font-semibold text-gray-700"
            >
              Dashboard
            </Link>

            <LogoutButton />
          </div>
        </header>

        <div className="mt-8 rounded-2xl bg-white p-6 shadow-sm">
          <p className="text-sm font-medium text-gray-500">
            Total responses
          </p>

          <p className="mt-2 text-4xl font-bold">
            {responses?.length ?? 0}
          </p>
        </div>

        <section className="mt-8 space-y-4">
          {responses?.length === 0 ? (
            <div className="rounded-2xl bg-white p-8 text-center shadow-sm">
              <p className="text-gray-500">
                No LLM responses yet.
              </p>
            </div>
          ) : (
            responses?.map((response) => {
              const model = Array.isArray(response.llm_models)
                ? response.llm_models[0]
                : response.llm_models;

              const providerRaw = model?.llm_providers;

              const provider = Array.isArray(providerRaw)
                ? providerRaw[0]
                : providerRaw;

              const request = Array.isArray(
                response.generation_requests
              )
                ? response.generation_requests[0]
                : response.generation_requests;

              return (
                <article
                  key={response.id}
                  className="rounded-2xl bg-white p-6 shadow-sm"
                >
                  <div className="flex flex-wrap items-start justify-between gap-4">
                    <div>
                      <h2 className="text-lg font-bold">
                        {provider?.name || "Unknown provider"}
                        {" · "}
                        {model?.name || "Unknown model"}
                      </h2>

                      <p className="mt-1 text-sm text-gray-500">
                        {model?.model_key || "No model key"}
                      </p>
                    </div>

                    <span className="rounded-full bg-gray-100 px-3 py-1 text-xs font-bold text-gray-600">
                      {request?.status || "Unknown status"}
                    </span>
                  </div>

                  <div className="mt-5 rounded-xl bg-gray-50 p-4">
                    <p className="text-xs font-bold uppercase tracking-wide text-gray-400">
                      Response
                    </p>

                    <p className="mt-2 whitespace-pre-wrap leading-6 text-gray-800">
                      {response.response_text || "No response text."}
                    </p>
                  </div>

                  <div className="mt-4 space-y-1 font-mono text-xs text-gray-400">
                    <p>Response: {response.id}</p>
                    <p>
                      Request:{" "}
                      {response.generation_request_id || "—"}
                    </p>
                  </div>
                </article>
              );
            })
          )}
        </section>
      </div>
    </main>
  );
}